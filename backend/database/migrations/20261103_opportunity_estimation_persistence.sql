-- Current estimation storage only. No legacy estimates are imported.
BEGIN;
SET LOCAL lock_timeout = '5s';
CREATE TABLE IF NOT EXISTS tbl_opportunity_estimation (
  estimation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id INTEGER NOT NULL REFERENCES tbl_opportunity(opportunity_id),
  resource_allocation JSONB NOT NULL,
  rate_snapshot JSONB NOT NULL,
  person_weeks JSONB NOT NULL,
  person_weeks_cost JSONB NOT NULL,
  estimation_name VARCHAR(500),
  isselected BOOLEAN NOT NULL DEFAULT FALSE,
  is_current BOOLEAN NOT NULL DEFAULT TRUE,
  created_by INTEGER NOT NULL,
  created_dt TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by INTEGER,
  updated_dt TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS tbl_opportunity_estimation_tracker (
  tracker_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LIKE tbl_opportunity_estimation INCLUDING DEFAULTS INCLUDING CONSTRAINTS
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_opportunity_estimation_selected
  ON tbl_opportunity_estimation (opportunity_id) WHERE isselected = TRUE;
CREATE INDEX IF NOT EXISTS idx_opportunity_estimation_named
  ON tbl_opportunity_estimation (opportunity_id) WHERE resource_allocation ? 'saved';
CREATE INDEX IF NOT EXISTS idx_opportunity_estimation_history
  ON tbl_opportunity_estimation_tracker (estimation_id, tracker_id DESC);
CREATE INDEX IF NOT EXISTS idx_opportunity_estimation_history_opportunity
  ON tbl_opportunity_estimation_tracker (opportunity_id);
COMMIT;
